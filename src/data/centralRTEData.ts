  "The official sources reviewed do not establish one complete, harmonised national dataset containing every RTE indicator for every year from 2014 through 2026.",
  "The following limitations must be recorded:",
  "1. Admissions under Section 12(1)(c): Parliamentary answers provide national totals for selected academic years, but a complete annual series through 2025-26 has not been established.",
  "2. School participation: The verified parliamentary school-count data cited here cover selected years and do not establish a complete national series from 2014 to 2026.",
  "3. Reimbursement: Claims, proposals, approvals, releases and expenditure are different measures. The relevant financial records must be checked separately.",
  "4. Discrepancies between parliamentary answers: Where two official answers report different figures for the same period, both source records should be retained until the difference is explained.",
  "5. UDISE+ data: These figures cover the broader school system and must not be presented as RTE-only data.",
  "6. State-specific implementation: Admission procedures, reimbursement practices, rules and administrative arrangements may differ across States and Union Territories.",
  "7. 2025\u201326 data: A final, comprehensive national dataset covering the full 2025-26 academic year has not been established from the sources cited in this report.",
